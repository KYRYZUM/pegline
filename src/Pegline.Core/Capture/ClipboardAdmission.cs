using System.Text.RegularExpressions;

namespace Pegline.Core.Capture;

/// <summary>Rules deciding whether a clipboard change may enter history at all.</summary>
public static partial class ClipboardAdmission
{
    /// <summary>Clipboard format registered by Pegline on its own copies so they are never re-captured.</summary>
    public const string OwnFormat = "Pegline.Internal.v1";

    public const int MaxTextChars = 1024 * 1024;
    public const long MaxImageBytes = 64L * 1024 * 1024;

    /// <summary>Formats that mark a copy as private (password managers, transient or concealed data).</summary>
    public static bool IsPrivate(IEnumerable<string> formats) => formats.Any(f => PrivateFormat().IsMatch(f) || f == OwnFormat);

    /// <summary>
    /// Windows clipboard history opt-out. A "CanIncludeInClipboardHistory" DWORD of 0 means the source app
    /// asked monitors not to keep the content.
    /// </summary>
    public static bool ExcludedFromHistory(ReadOnlySpan<byte> canIncludeInHistory) =>
        canIncludeInHistory.Length != 4 || BitConverter.ToUInt32(canIncludeInHistory) == 0;

    /// <summary>Text is admitted only when it contains something other than Unicode white space; the body stays exact.</summary>
    public static bool AdmitsText(string? value) =>
        !string.IsNullOrEmpty(value) && value.Length <= MaxTextChars && !value.Contains('\0') && value.Any(c => !char.IsWhiteSpace(c));

    /// <summary>Returns the normalized URL when the whole value is one http(s) address without credentials.</summary>
    public static string? PlainUrl(string? value)
    {
        if (string.IsNullOrEmpty(value) || value.Length > 8192 || value.Any(char.IsWhiteSpace))
            return null;
        if (!Uri.TryCreate(value, UriKind.Absolute, out var uri))
            return null;
        if (uri.Scheme != Uri.UriSchemeHttp && uri.Scheme != Uri.UriSchemeHttps)
            return null;
        if (uri.UserInfo.Length > 0 || uri.Host.Length == 0)
            return null;
        return uri.AbsoluteUri;
    }

    [GeneratedRegex("concealed|transienttype|autogeneratedtype|password|agilebits|ExcludeClipboardContentFromMonitorProcessing|Clipboard Viewer Ignore", RegexOptions.IgnoreCase)]
    private static partial Regex PrivateFormat();
}
